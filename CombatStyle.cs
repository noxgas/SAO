using UnityEngine;

/// <summary>
/// Combat styles for different character classes.
/// </summary>
public enum CombatStyle
{
    /// <summary>
    /// Melee combat - sword and shield or dual wield.
    /// </summary>
    Melee,

    /// <summary>
    /// Ranged combat - bows and arrows.
    /// </summary>
    Ranged,

    /// <summary>
    /// Magic combat - spells and abilities.
    /// </summary>
    Magic,

    /// <summary>
    /// Hybrid - combination of melee and magic.
    /// </summary>
    Hybrid,

    /// <summary>
    /// Stealth combat - sneaking and assassination.
    /// </summary>
    Stealth
}